// Pre-bundle the coach worker entry into a self-contained JS file.
// Next.js static export does NOT bundle Worker entries — `new Worker(new URL(...))`
// just copies the source file as-is, producing a raw .ts artifact with bare
// `@mlc-ai/web-llm` imports that the browser cannot execute.
//
// This script uses esbuild (now a dev dependency) to produce a single IIFE JS
// file with all imports resolved. The output goes to `public/_coachWorker.<hash>.js`
// so Next.js static export picks it up as a static asset.
//
// CRITICAL: Also generates a TypeScript manifest file that can be imported at
// build time, avoiding runtime fetch and ensuring the URL is known statically.

import { build } from "esbuild";
import { createHash } from "node:crypto";
import { writeFileSync, mkdirSync, existsSync, readdirSync, unlinkSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const webRoot = join(__dirname, "..");
const entry = join(webRoot, "app", "Worker", "coachWorker.ts");
const outDir = join(webRoot, "public");
const manifestTsPath = join(webRoot, "app", "lib", "coachEngine", "workerManifest.generated.ts");

if (!existsSync(outDir)) mkdirSync(outDir, { recursive: true });

// Clean old hashed worker files
for (const f of readdirSync(outDir)) {
  if (f.startsWith("_coachWorker.") && f.endsWith(".js")) {
    unlinkSync(join(outDir, f));
  }
}

const result = await build({
  entryPoints: [entry],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "es2022",
  write: false,
  minify: false,
  define: {
    "process.env.NODE_ENV": '"production"'
  },
  // External: nothing — we want everything bundled for the worker
  external: [],
  logLevel: "warning"
});

if (result.errors.length > 0) {
  console.error("Worker bundle failed:", result.errors);
  process.exit(1);
}

const code = result.outputFiles[0].text;
// CRITICAL: Use Buffer.byteLength for accurate UTF-8 byte count
const bytes = Buffer.byteLength(code, "utf8");
const hash = createHash("sha256").update(code).digest("hex").slice(0, 16);
const outName = `_coachWorker.${hash}.js`;
const outPath = join(outDir, outName);

writeFileSync(outPath, code, "utf-8");

// Write a stable manifest so the app can find the hashed filename
const manifestPath = join(outDir, "_coachWorker.manifest.json");
writeFileSync(manifestPath, JSON.stringify({ file: outName, hash, bytes }) + "\n", "utf-8");

// CRITICAL: Generate TypeScript manifest for build-time import
// This avoids runtime fetch and ensures the URL is known statically
const tsManifest = `// AUTO-GENERATED by scripts/bundle-coach-worker.mjs
// DO NOT EDIT — this file is regenerated on every build.
export const COACH_WORKER_URL = "/${outName}";
export const COACH_WORKER_HASH = "${hash}";
export const COACH_WORKER_BYTES = ${bytes};
`;
writeFileSync(manifestTsPath, tsManifest, "utf-8");

console.log(`Worker bundled: ${outName} (${bytes} bytes)`);
console.log(`Manifest generated: ${manifestTsPath}`);
